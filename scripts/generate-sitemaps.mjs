/**
 * Sitemap generator — reads from pseo-data cluster keywords
 * Run: node scripts/generate-sitemaps.mjs
 */

import { writeFileSync, mkdirSync } from 'fs';
import { join } from 'path';

// Inline slug generator (mirrors pseo-data.ts)
function toSlug(k) {
  return k.toLowerCase().replace(/[^a-z0-9\s-]/g, '').replace(/\s+/g, '-').replace(/-+/g, '-').trim();
}

// Import the compiled keyword data
// Run `npx tsx scripts/export-slugs.ts` first if needed, or use the JSON export
import { createRequire } from 'module';
const require = createRequire(import.meta.url);

const BASE_URL = 'https://www.humanifylab.com';
const MAX_URLS = 50000;
const OUTPUT_DIR = './public/sitemaps';
const NOW = new Date().toISOString();

const MAIN_PAGES = [
  { loc: BASE_URL, priority: 1.0, changefreq: 'daily' },
  { loc: `${BASE_URL}/pricing`, priority: 0.9, changefreq: 'weekly' },
  { loc: `${BASE_URL}/faq`, priority: 0.8, changefreq: 'weekly' },
  { loc: `${BASE_URL}/contact`, priority: 0.7, changefreq: 'monthly' },
  { loc: `${BASE_URL}/responsible-use`, priority: 0.6, changefreq: 'monthly' },
  { loc: `${BASE_URL}/terms`, priority: 0.5, changefreq: 'monthly' },
  { loc: `${BASE_URL}/privacy`, priority: 0.5, changefreq: 'monthly' },
];

function urlEntry(url) {
  return `
  <url>
    <loc>${url.loc}</loc>
    <lastmod>${NOW}</lastmod>
    <changefreq>${url.changefreq}</changefreq>
    <priority>${url.priority.toFixed(1)}</priority>
  </url>`;
}

function sitemapXml(urls) {
  return `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls.map(urlEntry).join('')}
</urlset>`;
}

function sitemapIndexXml(files) {
  const entries = files.map(f => `
  <sitemap>
    <loc>${BASE_URL}/sitemaps/${f}</loc>
    <lastmod>${NOW}</lastmod>
  </sitemap>`).join('');
  return `<?xml version="1.0" encoding="UTF-8"?>
<sitemapindex xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${entries}
</sitemapindex>`;
}

function chunk(arr, size) {
  const out = [];
  for (let i = 0; i < arr.length; i += size) out.push(arr.slice(i, i + size));
  return out;
}

async function run() {
  mkdirSync(OUTPUT_DIR, { recursive: true });

  // Load slugs from the exported JSON (generated by `npx tsx scripts/export-slugs.ts`)
  let slugData;
  try {
    slugData = require('../public/data/pseo-slugs.json');
  } catch {
    console.error('❌ public/data/pseo-slugs.json not found. Run: npx tsx scripts/export-slugs.ts first.');
    process.exit(1);
  }

  const { bypass, humanizer, howto, usecase } = slugData;

  const keywordUrls = [
    ...bypass.map(s => ({ loc: `${BASE_URL}/${s}`, priority: 0.9, changefreq: 'weekly' })),
    ...humanizer.map(s => ({ loc: `${BASE_URL}/${s}`, priority: 0.85, changefreq: 'weekly' })),
    ...howto.map(s => ({ loc: `${BASE_URL}/${s}`, priority: 0.8, changefreq: 'weekly' })),
    ...usecase.map(s => ({ loc: `${BASE_URL}/${s}`, priority: 0.75, changefreq: 'weekly' })),
  ];

  const allUrls = [...MAIN_PAGES, ...keywordUrls];
  console.log(`📊 Total URLs: ${allUrls.length.toLocaleString()}`);

  const chunks = chunk(allUrls, MAX_URLS);
  const files = [];

  for (let i = 0; i < chunks.length; i++) {
    const filename = `sitemap-${i + 1}.xml`;
    writeFileSync(join(OUTPUT_DIR, filename), sitemapXml(chunks[i]), 'utf-8');
    files.push(filename);
    console.log(`✓ ${filename} — ${chunks[i].length.toLocaleString()} URLs`);
  }

  writeFileSync(join(OUTPUT_DIR, 'sitemap-index.xml'), sitemapIndexXml(files), 'utf-8');
  console.log(`✓ sitemap-index.xml`);

  writeFileSync('./public/sitemap.xml', `<?xml version="1.0" encoding="UTF-8"?>
<sitemapindex xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
  <sitemap>
    <loc>${BASE_URL}/sitemaps/sitemap-index.xml</loc>
    <lastmod>${NOW}</lastmod>
  </sitemap>
</sitemapindex>`, 'utf-8');
  console.log(`✓ public/sitemap.xml`);
  console.log(`\n✅ Done — ${files.length} sitemap file(s) generated.`);
}

run().catch(console.error);
